      {
          last_report += 100;

          printf("ACC: %.3f %.3f %.3f  GYRO: %.2f %.2f %.2f\r\n",
                 imu.acc_x_g,
                 imu.acc_y_g,
                 imu.acc_z_g,
                 imu.gyro_x_dps,
                 imu.gyro_y_dps,
                 imu.gyro_z_dps);
      }
